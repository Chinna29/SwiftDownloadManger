'use strict';
const fsp = require('fs/promises');
const path = require('path');
const crypto = require('crypto');

/**
 * Writes a browser cookie jar (as sent by the extension) to a Netscape-format
 * cookies.txt that yt-dlp understands. Returns the file path, or null when the
 * jar is empty. Files live under <dir> and are deleted by the caller when the
 * job finishes, since they hold session secrets.
 */
async function writeCookieFile(dir, jar, name) {
  if (!Array.isArray(jar) || jar.length === 0) return null;
  const lines = ['# Netscape HTTP Cookie File', '# Generated by SwiftFetch for a single download; deleted afterwards.', ''];
  for (const c of jar) {
    if (!c || typeof c.name !== 'string') continue;
    const domain = String(c.domain || '').trim();
    if (!domain) continue;
    const includeSub = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const cookiePath = c.path || '/';
    const secure = c.secure ? 'TRUE' : 'FALSE';
    const expiry = c.expirationDate ? Math.floor(Number(c.expirationDate)) : 0;
    const prefix = c.httpOnly ? '#HttpOnly_' : '';
    const value = String(c.value ?? '').replace(/[\r\n\t]/g, '');
    lines.push([prefix + domain, includeSub, cookiePath, secure, expiry, c.name, value].join('\t'));
  }
  if (lines.length <= 3) return null;
  await fsp.mkdir(dir, { recursive: true });
  const file = path.join(dir, (name || crypto.randomUUID()) + '.txt');
  await fsp.writeFile(file, lines.join('\n') + '\n', { encoding: 'utf8', mode: 0o600 });
  return file;
}

async function removeCookieFile(file) {
  if (!file) return;
  await fsp.rm(file, { force: true }).catch(() => {});
}

module.exports = { writeCookieFile, removeCookieFile };
